// DP BOTTOM UP APPROACH TABULATION

// IF WE OBSERVE A MATRIX ALREADY SOLVED, SAY 3X3 MATRIX
// {6, 3, 1}
// {3, 2, 1}
// {1, 1, 1}
// WE CAN OBSERVE, THAT FOR A GIVEN CELL, THE NUMBER OF
// PATHS FROM THAT CELL TO OUR DESTINATION (M - 1, N - 1)
// IS THE RESULT OF SUM THE DOWN AND RIGHT CELL PATHS, EXCEPT
// FOR THE BASE CASE (M - 1, N - 1) WHICH LOGICALLY THE PATH
// FROM OUR TARGET CELL TO OUR TARGET CELL SEEMS TO BE 0,
// BUT WE KEEP 1, SO THE MATH WORK OUT.
//
// ANOTHER THING WE CAN OBSERVE, IS BY THE CONDITIONS IN TURNS OUT
// THE LAST ROW AND THE LAST COLUMN VALUES ARE ALL 1, IT MAKES SENSE
// BECAUSE FROM ANY OF THOSE CELLS WE ONLY CAN MOVE TO THE RIGHT (IN
// THE CASE OF ROWS) OR DOWN (IN THE CASE OF COLUMNS), LET'S SEE
// THE CELL M[1][1], WHICH VALUE IS 2, THAT VALUE IS THE RESULT OF
// M[1+1][1] + M[1][1+1], SO IT SEEMS WE CAN FILL A ROW FROM RIGHT
// TO LEFT STARTING WITH OUR BASE CASES, OUR LAST ROW AND COLUMN
// WITH 1 VALUES. IF WE SEE M[1][0], IS THE RESULT OF M[1+1][0] AND
// M[1][0+1], THEN THIS ROW IS USED TO FILL UP THE NEXT ROW
// AND SO ON.
//
// I THINK I NEED TO CARE ABOUT THE BASE CASES, BECAUSE
// FOR THIS PROBLEM IT WORKS TO HAVE LAST ROW AND COLUMN
// FILLED WITH 1 ONES, BUT IT IS POSSIBLE THIS CONDITION
// DONT WORK FOR ANOTHER PROBLEMS, THE KEY IS TO SEE
// HOW THE RECURSIVE APPROACH FILLS THE MATRIX, THEN FROM
// THAN WE CAN FIGURE OUT OUR BASE CASES OR AT LEAST
// TO HAVE AN IDEA OF THEM.

// IN REALITY I THINK WE ONLY NEED, TWO ROWS OF SIZE N
// REPLACING THE SECOND ONE WITH THE FIRST ONE
// WHEN WE HAVE FINISHED THE FIRST ONE.

// PSEUDOCODE:
// WE INITIALIZE OUR FIRST ROW OF SIZE N, WITH
// ALL ELEMENTS TO 1,
// WE INITIALIZE A SECOND ROW OF SIZE N, WITH
// ALL ELEMENTS TO 0, EXCEPT FOR THE LAST ONE,
// SET UP TO 1.
// WE ITERATE AS MANY ROWS WE HAVE UNTIL 0
// (IT'S LIKE IF WE WERE BUILDING THE MATRIX FROM
// THE BOTTOM TO UP, ROW BY ROW FROM RIGHT TO LEFT)
// THEN WE NEED TO FILL OUR SECOND ROW STARTING
// AT N - 2 UNTIL N = 0, TO COMPUTE A NEW VALUE
// WE NEED TO ACCESS THE DOWN VALUE PLUS THE RIGHT
// VALUE, WHICH ARE PREV_ROW[M] + CURRENT_ROW[N+1]
// RESPECTIVELY, ONCE WE FINISHED OUR ROW, WE NEED
// TO REPLACE OUR PREVIOUS ROW WITH OUR CURRENT
// ROW TO FILL THE NEXT ROW.
//
// THE RESULT IS AT CURRENT ROW[0]

class Solution {
   public:
    int uniquePaths(int m, int n) {
        vector<int> prevRow(n, 1);
        vector<int> currRow(n);
        currRow[n - 1] = 1;

        for (int r = m - 2; r >= 0; r--) {
            for (int c = n - 2; c >= 0; c--) {
                currRow[c] = prevRow[c] + currRow[c + 1];
            }
            prevRow = currRow;
        }

        return prevRow[0];
    }
};
